import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { DEGREES, intervalsForQuality } from './intervals.js';
import { spellDegree } from './notes.js';

const TRIADS = new Map([
  ['M3,P5',''],['m3,P5','m'],['m3,d5','°'],['M3,A5','aug'],
  ['M2,P5','sus2'],['P4,P5','sus4'],['M3,d5','(♭5)'],['m3,A5','m(♯5)'],
]);
const FOUR_NOTES = new Map([
  ['M3,P5,M7','Δ7'],['m3,P5,m7','m7'],['M3,P5,m7','7'],['m3,d5,m7','ø7'],
  ['m3,d5,d7','°7'],['m3,P5,M7','mΔ7'],['M3,A5,M7','Δ7(♯5)'],
  ['M3,A5,m7','7(♯5)'],['M3,d5,m7','7(♭5)'],['M3,d5,M7','Δ7(♭5)'],
  ['m3,d5,M7','°Δ7'],['M3,P5,M6','6'],['m3,P5,M6','m6'],
  ['m3,P5,m6','m(♭6)'],['P4,P5,m7','7sus4'],['M3,P5,9','add9'],
  ['M3,P5,P4','add4'],['m3,P5,P4','m(add4)'],
]);
const unicode = text => text.replaceAll('b','♭').replaceAll('#','♯');

// Use the same expanded playlist as analyzePlaylist: each symbol counts once,
// including repeats; slash basses and extra tensions do not create extra cards.
export function chordToneFrequencies(playlist) {
  const groups = {triads:new Map(),fourNote:new Map()};
  let occurrences=0;
  const add=(kind,root,quality,intervals)=>{
    const tones=intervals.map(interval=>spellDegree(root,DEGREES.get(interval)));
    if(tones.some(tone=>tone===null))return;
    const chord=unicode(root)+quality;
    const previous=groups[kind].get(chord);
    groups[kind].set(chord,{root:unicode(root),quality,notes:[unicode(root),...tones.map(unicode)],count:(previous?.count??0)+1});
  };
  for(const song of playlist.songs)for(const measure of song.music.measures)for(const chord of measure){
    if(chord===null)continue;
    const match=/^([A-G][#b]?)([^/]*)(?:\/[A-G][#b]?)?$/.exec(chord);
    if(!match)throw new Error(`Invalid chord: ${chord}`);
    occurrences++;
    const [,root,quality]=match;
    const intervals=intervalsForQuality(quality);
    const third=intervals.find(interval=>['M2','m3','M3','P4'].includes(interval));
    const fifth=intervals.find(interval=>['d5','P5','A5'].includes(interval));
    // Power chords and unspecified altered fifths do not determine a triad.
    if(!third||!fifth)continue;
    const triad=TRIADS.get(`${third},${fifth}`);
    if(triad===undefined)throw new Error(`Unknown triad in ${chord}`);
    add('triads',root,triad,[third,fifth]);
    const fourth=['d7','m7','M7','M6','m6','9','P4'].find(interval=>interval!==third&&intervals.includes(interval));
    if(!fourth)continue;
    const four=FOUR_NOTES.get(`${third},${fifth},${fourth}`);
    if(four===undefined)throw new Error(`Unknown four-note chord in ${chord}`);
    add('fourNote',root,four,[third,fifth,fourth]);
  }
  const ranked=group=>[...group.values()].sort((a,b)=>b.count-a.count||((a.root+a.quality)<(b.root+b.quality)?-1:1));
  return {songs:playlist.songs.length,occurrences,triads:ranked(groups.triads),fourNote:ranked(groups.fourNote)};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  if(process.argv.length!==3)throw new Error('Usage: node tools/ireal-analysis/src/chord-tones.js expanded-playlist.json');
  const input=readFileSync(process.argv[2],'utf8');const result=chordToneFrequencies(JSON.parse(input));
  const header='// SPDX-FileCopyrightText: Copyright (c) 2026 Wataru Ashihara <wataash0607@gmail.com>\n// SPDX-License-Identifier: Apache-2.0\n// Generated by tools/ireal-analysis/src/chord-tones.js. Counts are expanded Jazz 1460 occurrences.\n';
  const rows=rows=>'[\n'+rows.map(row=>'  '+JSON.stringify(row)).join(',\n')+'\n] as const;\n';
  process.stdout.write(header+`export const CHORD_TONE_SOURCE = ${JSON.stringify({playlist:'Jazz 1460',songs:result.songs,occurrences:result.occurrences,reader:'662106fe60ea3f91574ddf98df0e2468a3d89e6a',sha256:createHash('sha256').update(input).digest('hex')})} as const;\n`+'export const TRIAD_FREQUENCIES = '+rows(result.triads)+'export const FOUR_NOTE_FREQUENCIES = '+rows(result.fourNote));
}
